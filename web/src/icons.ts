const isIconName = (name: string): name is keyof typeof icons =>
  Object.hasOwn(icons, name);

export const iconNames = Object.keys(icons).sort();

const renderNode = ([tag, attributes]: IconNode[number]) => {
  switch (tag) {
    case "path":
      return svg`<path d=${attributes.d ?? ""}></path>`;
    case "circle":
      return svg`<circle cx=${attributes.cx ?? 0} cy=${attributes.cy ?? 0} r=${attributes.r ?? 0}></circle>`;
    case "rect":
      return svg`<rect x=${attributes.x ?? 0} y=${attributes.y ?? 0} width=${attributes.width ?? 0} height=${attributes.height ?? 0} rx=${attributes.rx ?? 0}></rect>`;
    case "line":
      return svg`<line x1=${attributes.x1 ?? 0} y1=${attributes.y1 ?? 0} x2=${attributes.x2 ?? 0} y2=${attributes.y2 ?? 0}></line>`;
    case "polyline":
      return svg`<polyline points=${attributes.points ?? ""}></polyline>`;
    case "polygon":
      return svg`<polygon points=${attributes.points ?? ""}></polygon>`;
    case "ellipse":
      return svg`<ellipse cx=${attributes.cx ?? 0} cy=${attributes.cy ?? 0} rx=${attributes.rx ?? 0} ry=${attributes.ry ?? 0}></ellipse>`;
    default:
      return svg``;
  }
};

// An icon by name, falling back to a dot for names the panel doesn't know.
export const icon = (name: string): SVGTemplateResult => {
  const node = isIconName(name) ? icons[name] : CircleDot;

  return svg`<svg class="icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${node.map(renderNode)}</svg>`;
};
